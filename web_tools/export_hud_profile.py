"""Export the HUD calibration and templates to web/ for the browser scanner:

  .venv\\Scripts\\python.exe web_tools\\export_hud_profile.py"""
import json
import sys
from pathlib import Path
import cv2
import numpy as np

WEB = Path(__file__).resolve().parents[1]/'web'
ROOT = WEB.parent
sys.path.insert(0, str(ROOT))
import video_analysis as va  # noqa: E402

SETTINGS = json.loads((ROOT/'settings.json').read_text(encoding='utf-8-sig'))


def main():
    assets = WEB/'assets'
    assets.mkdir(exist_ok=True)
    with np.load(ROOT/'assets'/'digit_templates.npz') as templates:
        values, labels = templates['values'], templates['labels']
    # 0..1 floats stored as bytes (error under 0.002 per pixel; the match thresholds are 0.24 / 0.015).
    np.round(values*255).astype(np.uint8).tofile(assets/'digits.bin')
    combo = cv2.imread(str(ROOT/'assets'/'combo_word.png'), cv2.IMREAD_GRAYSCALE)
    combo.tofile(assets/'combo_word.bin')

    profile = {
        'name': 'CODM spectator HUD (default calibration)',
        'scanner_version': va.SCANNER_VERSION,
        'note': 'Regions are [left, top, right, bottom] fractions of the frame, cropped with '
                'int(size*fraction) like video_analysis.crop.',
        'counter': {
            'layouts': [list(l) for l in va.COUNTER_LAYOUTS],
            'layout_names': ['respawn modes (bottom-right panel)', 'round modes (taller panel with COMBO row)'],
            'calibration_samples': 40,
            'min_hits': 5,
            'tile': {'size': [180, 130], 'resize': [147, 99], 'offset': [15, 15], 'threshold': 180},
            'glyph': {'ink_rows': [25, 105], 'min_column_ink': 2, 'max_column_gap': 3,
                      'min_width': 8, 'min_height': 35, 'size': [24, 48]},
            'max_score': .24,
            'min_margin': .015,
            'max_digits': 3,
        },
        'digit_templates': {'file': 'assets/digits.bin', 'dtype': 'uint8', 'scale': 255,
                            'shape': list(values.shape), 'labels': labels.tolist()},
        'name': {
            'x_range': [.80, .90],
            'size': [120, 24],
            'mask_level': 170,
            'mask_overlap': .6,
            'match': va.NAME_MATCH,
        },
        'hp': {
            'layouts': [list(l) for l in va.HP_LAYOUTS],
            'level': va.HP_LEVEL,
            'calibration_samples': 30,
            'full_score': .8,
            'dim_offset': 35,
            'min_dim_level': 150,
        },
        'combo': {
            'letter_box': [.8160, .785, .8245, .806],
            'digit_box': [.8275, .785, .836, .806],
            'digit_shifts': [-.002, -.001, 0, .001, .002],
            'patch_size': [16, 24],
            'zero': va.COMBO_ZERO,
            'word_template': {'file': 'assets/combo_word.bin', 'shape': list(combo.shape), 'height': 1080},
            'word_origin': list(va.COMBO_WORD),
            'search_box': [.760, .770, .865, .825],
            'min_match': .6,
            'min_found': 5,
        },
        'rules': {k: SETTINGS[k] for k in ('min_kills', 'window', 'max_gap', 'pre', 'post', 'interval',
                                           'map_shift', 'death_guard', 'respawn_settle')},
    }
    (WEB/'hud-profile.json').write_text(json.dumps(profile, indent=2)+'\n', encoding='utf-8')
    print(f'Wrote {WEB/"hud-profile.json"}, {assets/"digits.bin"} ({values.shape[0]} templates), '
          f'{assets/"combo_word.bin"} {combo.shape}')
    export_live()


def export_live():
    """web/live-profile.json: the live-recording constants and the shrunk killcam titles."""
    import live_analysis as live  # noqa: E402
    import numpy as np
    digits = np.load(live.ASSETS/'counter_digits.npy')
    popup = np.load(live.ASSETS/'popup_digits.npy')
    titles = {}
    for key, name in (('killcam', 'killcam.png'), ('killed_by', 'killed_by.png')):
        t = live.load_title(name)
        titles[key] = {'shape': list(t.shape), 'data': t.ravel().tolist()}
    profile = {
        'note': 'Generated by web_tools/export_hud_profile.py from live_analysis.py. Regions are [left, top, '
                'right, bottom] fractions of the game picture (black bars removed, scaled to 1080 rows), '
                'cropped with int(size*fraction).',
        'live_version': live.LIVE_VERSION,
        'interval': live.INTERVAL,
        'killcam_roi': list(live.KILLCAM_ROI),
        'killed_by_roi': list(live.KILLED_BY_ROI),
        'spectate_roi': list(live.SPECTATE_ROI),
        'away_score': live.AWAY_SCORE,
        'spectate_lit': live.SPECTATE_LIT,
        'title_scale': live.TITLE_SCALE,
        'locate_samples': 240,
        'titles': titles,
        'counter_roi': list(live.COUNTER_ROI),
        'counter_inner': list(live.COUNTER_INNER),
        'counter_conf': live.COUNTER_CONF,
        'counter_fonts': list(live.COUNTER_FONTS),
        'counter_band': list(live.COUNTER_BAND),
        'counter_size': list(live.COUNTER_SIZE),
        'counter_digit': live.COUNTER_DIGIT,
        'icon_slot': list(live.ICON_SLOT),
        'icon_pitch': live.ICON_PITCH,
        'icon_lit': live.ICON_LIT,
        'popup_roi': list(live.POPUP_ROI),
        'popup_conf': live.POPUP_CONF,
        'popup_sure': live.POPUP_SURE,
        'popup_digits': {'shape': list(popup.shape), 'data': [d.ravel().tolist() for d in popup]},
        'counter_digits': {'shape': list(digits.shape), 'data': [d.ravel().tolist() for d in digits]},
        'streaks': live.load_streaks(),
    }
    (WEB/'live-profile.json').write_text(json.dumps(profile)+'\n', encoding='utf-8')
    print(f'Wrote {WEB/"live-profile.json"}')


if __name__ == '__main__':
    main()
